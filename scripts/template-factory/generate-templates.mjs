#!/usr/bin/env node
/**
 * Generates assets/templates/<id>/template.json + FABRICATION.md and index.json
 * from catalog.mjs. Does NOT create .mogrt binaries.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { designCount, expandCatalog } from "./catalog.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const templatesRoot = join(root, "assets/templates");

const catalog = expandCatalog();
mkdirSync(templatesRoot, { recursive: true });

const index = {
  version: 1,
  generatedAt: "deterministic",
  designCount: designCount(),
  templateCount: catalog.length,
  templates: [],
};

for (const tpl of catalog) {
  const dir = join(templatesRoot, tpl.id);
  mkdirSync(dir, { recursive: true });
  const jsonPath = join(dir, "template.json");
  writeFileSync(jsonPath, JSON.stringify(tpl, null, 2) + "\n", "utf8");

  const fab = [
    `# Fabrication — ${tpl.name}`,
    "",
    `- **id**: \`${tpl.id}\``,
    `- **aspect**: ${tpl.aspect}`,
    `- **status**: ${tpl.status}`,
    `- **mogrt cible**: \`${tpl.mogrt}\` (à livrer dans ce dossier)`,
    "",
    "## Propriétés maîtres (Essential Graphics)",
    "",
    ...tpl.parameters.map(
      (p) =>
        `- \`${p.masterPropertyName}\` (${p.type}) — ${typeof p.label === "string" ? p.label : p.label.en}`
    ),
    "",
    "## Notes",
    "",
    tpl.fabNotes || "(aucune)",
    "",
    "Voir docs/templates/AUTHORING.md pour les contraintes Premiere / Graphiques essentiels.",
    "",
  ].join("\n");
  writeFileSync(join(dir, "FABRICATION.md"), fab, "utf8");

  index.templates.push({
    id: tpl.id,
    name: tpl.name,
    category: tpl.category,
    aspect: tpl.aspect,
    status: tpl.status,
    path: `${tpl.id}/template.json`,
  });
}

writeFileSync(join(templatesRoot, "index.json"), JSON.stringify(index, null, 2) + "\n", "utf8");

// Embedded runtime catalog for UXP (no filesystem required for built-ins)
const tsOut = join(root, "src/features/motion/templates/generatedCatalog.ts");
const tsBody = `/* AUTO-GENERATED by scripts/template-factory/generate-templates.mjs — do not edit */
import type { MotionTemplateDefinition } from "../templateTypes";

export const GENERATED_TEMPLATES: MotionTemplateDefinition[] = ${JSON.stringify(catalog, null, 2)};

export const GENERATED_TEMPLATE_COUNT = GENERATED_TEMPLATES.length;
`;
writeFileSync(tsOut, tsBody, "utf8");

console.log(
  `[templates:generate] ${catalog.length} templates (${designCount()} designs × aspects) → assets/templates/ + generatedCatalog.ts`
);
